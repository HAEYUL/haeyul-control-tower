const PURPOSE_GUIDE = {
  '신메뉴·시즌메뉴': '프레이밍: "새로 추가했습니다"가 아니라 "제철이 왔습니다". 계절감을 강조한다.',
  '가족모임·부모님모시기': '프레이밍: 효도를 강요하지 않는다. 모시고 오기 좋은 구체적 이유(자극적이지 않음, 층고, 주차, 식후 앉을 자리)를 보여준다.',
  '공간·뷰 소구(SNS)': '프레이밍: 음식보다 창밖과 층고, 공간의 첫인상이 먼저 보이게 한다.',
  '보양·원기회복 시즌': '프레이밍: "기력을 채운다"가 아니라 "부담 없이 채운다". 무겁고 느끼한 기존 보양식의 반대편에 선다.',
  자유주제: '주어진 컨셉에 맞게 자유롭게 구성하되, 브랜드 톤을 벗어나지 않는다.',
}

const COMMON_RULES = `공통 규칙:
- "몸에 좋다", "건강에 좋다", "효능이 있다" 같은 효능 주장 표현은 절대 쓰지 마세요 (식품 표시광고법 위반 소지).
- "몇 년 전통", "몇 대째" 같은 확인되지 않은 표현은 쓰지 마세요.
- 이미지/영상에 들어갈 한글 카피가 있다면 짧고 담백하게, 과장된 감탄사나 이모티콘 없이 쓰세요.`

let client

function getClient() {
  if (!client) {
    client = new Anthropic()
  }
  return client
}

export async function generateContentBrief({ store, contentType, purpose, concept }) {
  const storeInfo = STORES[store]
  if (!storeInfo) throw new Error('알 수 없는 매장입니다')

  const purposeGuide = PURPOSE_GUIDE[purpose] || PURPOSE_GUIDE.자유주제

  const isImage = contentType === '이미지'

  const system = isImage
    ? `당신은 ${store}의 포스터·홍보 이미지를 기획하는 비주얼 디렉터입니다.

${storeInfo}

${purposeGuide}

${COMMON_RULES}

작업: 아래 컨셉을 바탕으로, Midjourney·DALL-E 등 이미지 생성 도구에 바로 붙여넣을 수 있는 이미지 프롬프트를 3개 만드세요. 각 프롬프트는 서로 다른 구도/앵글을 제안하고, 조명·색감·분위기·피사체를 구체적으로 묘사하세요 (영어로 작성). 프롬프트마다 앞에 어떤 컨셉인지 한 줄 한국어 설명을 붙이세요.

출력 형식:
1) [한 줄 설명]
프롬프트: "..."

2) [한 줄 설명]
프롬프트: "..."

3) [한 줄 설명]
프롬프트: "..."`
    : `당신은 ${store}의 홍보 영상을 기획하는 영상 디렉터입니다.

${storeInfo}

${purposeGuide}

${COMMON_RULES}

작업: 아래 컨셉을 바탕으로 15~30초 분량의 짧은 홍보 영상 스토리보드를 만드세요. 4~6개 장면으로 구성하고, 각 장면마다 화면 설명(구도·움직임·피사체)과 자막/카피, 예상 길이(초)를 적으세요. Google Flow 같은 AI 영상 생성 도구에 바로 활용할 수 있도록 장면 설명은 구체적으로 쓰세요.

출력 형식:
장면 1 (n초): [화면 설명]
자막: "..."

장면 2 (n초): [화면 설명]
자막: "..."

(이하 동일 형식으로 계속)`

  const userPrompt = `컨셉/요청 사항: ${concept || '(특별한 요청 없음, 목적에 맞게 자유롭게 구성)'}`

  const response = await getClient().messages.create({
    model: 'claude-sonnet-5',
    max_tokens: 3072,
    system,
    messages: [{ role: 'user', content: userPrompt }],
  })

  const textBlock = response.content.find((block) => block.type === 'text')
  if (!textBlock?.text) {
    throw new Error('기획안을 생성하지 못했습니다. 다시 시도해주세요.')
  }

  return textBlock.text.trim()
}
